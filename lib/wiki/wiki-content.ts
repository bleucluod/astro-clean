export function getWikiCategory(categoryId: WikiCategoryId): WikiCategory | null {
  return wikiCategories.find((category) => category.id === categoryId) ?? null;
}

export function getWikiArticle(slug: string): WikiArticle | null {
  return wikiArticles.find((article) => article.slug === slug) ?? null;
}

export function getRelatedWikiArticles(article: WikiArticle): WikiArticle[] {
  return article.relatedSlugs
    .map((slug) => getWikiArticle(slug))
    .filter((relatedArticle): relatedArticle is WikiArticle => relatedArticle !== null);
}
