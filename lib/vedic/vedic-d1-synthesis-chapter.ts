const namePrefix = (name: string) => name ? name + '، ' : '';
const reliable = (row: Row | undefined | null): row is Row & {signIndex:number;houseNumber:number} =>
  Boolean(row && row.signIndex !== null && row.houseNumber !== null && !row.isBoundaryUncertain);
const near = (view: VedicD1NorthView, id: Classical) =>
  view.rows.find(row => row.id === id);

export type VedicD1SynthesisResult = { paragraphsFa: string[]; evidence: VedicD1FactualEvidence[]; archetype: 'crossroads-5-7' | 'shared-effort-11-8' | 'general' | 'uncertain' };
