function labeledCampaign(
  href: Parameters<typeof campaign>[0],
  card1Text: string,
  card1Label: string,
  card2Text: string,
  card2Label: string,
): EditorialStickyCtaCampaign {
  const base = campaign(href, card1Label, card1Text, card2Text);

  return {
    ...base,
    cards: [
      { ...base.cards[0], label: card1Label },
      { ...base.cards[1], label: card2Label },
    ],
  };
}

