export type EditorialStickyCtaCard = {
  readonly at: number;
  readonly text: string;
  readonly label?: string;
};

export type EditorialStickyCtaCampaign = {
  readonly href: string;
  readonly label: string;
  readonly cards: readonly [EditorialStickyCtaCard, EditorialStickyCtaCard];
};

const DEFAULT_FIRST_REVEAL = 0.22;
const DEFAULT_SECOND_REVEAL = 0.6;
const REPORT_FIRST_REVEAL = 0.44;
const REPORT_SECOND_REVEAL = 0.8;

function campaign(
  href: string,
  label: string,
  firstText: string,
  secondText: string,
  firstReveal = DEFAULT_FIRST_REVEAL,
  secondReveal = DEFAULT_SECOND_REVEAL,
): EditorialStickyCtaCampaign {
  return {
    href,
    label,
    cards: [
      { at: firstReveal, text: firstText },
      { at: secondReveal, text: secondText },
    ],
  };
}

