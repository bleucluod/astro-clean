function parseArgs(argv = process.argv.slice(2)) {
  const confirmArg = argv.find((arg) => arg.startsWith("--confirm="));
  return {
    apply: argv.includes("--apply"),
    compact: argv.includes("--compact"),
    selfCheck: argv.includes("--self-check"),
    resumeVerify: argv.includes("--resume-verify"),
    confirm: confirmArg ? confirmArg.slice("--confirm=".length) : null,
  };
}

function normalizeText(value) {
  return String(value ?? "")
    .replace(/\u200c/g, " ")
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/\s+/g, " ")
    .trim();
}

function jsonArray(value) {
  return Array.isArray(value) ? value : [];
}

function deepClone(value) {
  return JSON.parse(JSON.stringify(value));
}

function directChartLinksInText(text) {
  const source = String(text ?? "");
  const tokenMatches = source.match(/\[\[page:\/chart\|[^\]\r\n]+\]\]/g) ?? [];
  const markdownMatches = source.match(/\[[^\]\r\n]+\]\(\/chart\)/g) ?? [];
  return tokenMatches.length + markdownMatches.length;
}

function internalLinkCount(text) {
  const source = String(text ?? "");
  const tokens = source.match(/\[\[(?:article:[^\]]+|page:[^\]]+)\]\]/g) ?? [];
  const markdown = source.match(/\[[^\]\r\n]+\]\(\/(?:chart|compare|sky|wiki)(?:\/[^)]*)?\)/g) ?? [];
  return tokens.length + markdown.length;
}

function structuredTexts(article) {
  return [
    String(article.intro ?? ""),
    ...jsonArray(article.key_points).map(String),
    ...jsonArray(article.sections).flatMap((section) => [
      ...jsonArray(section?.paragraphs).map(String),
      ...jsonArray(section?.bullets).map(String),
    ]),
  ];
}

function structuredChartCount(article) {
  return structuredTexts(article).reduce((sum, text) => sum + directChartLinksInText(text), 0);
}

function bodyChartCount(article) {
  return directChartLinksInText(article.body_markdown ?? "");
}

function pageToken(anchor) {
  return `[[page:/chart|${anchor}]]`;
}

function articleToken(stableId) {
  return `[[article:${stableId}]]`;
}

function findSection(article, heading) {
  const matches = jsonArray(article.sections)
    .map((section, index) => (normalizeText(section?.title) === normalizeText(heading) ? { section, index } : null))
    .filter(Boolean);
  if (matches.length !== 1) {
    throw new Error(`${article.slug}: expected exactly one H2 "${heading}", found ${matches.length}`);
  }
  return matches[0];
}

function assertReferencePrefix(article, plan, paragraph) {
  if (!plan.referencePrefix) return;
  const actual = normalizeText(paragraph);
  const expected = normalizeText(plan.referencePrefix);
  if (!actual.startsWith(expected)) {
    throw new Error(`${article.slug}: locator drift under H2 "${plan.heading}". Expected paragraph prefix "${plan.referencePrefix}"`);
  }
}

function replaceBodyParagraph(bodyMarkdown, before, after, label) {
  const body = String(bodyMarkdown ?? "");
  const exactParts = body.split(before);
  if (exactParts.length - 1 === 1) return exactParts.join(after);
  if (exactParts.length - 1 > 1) throw new Error(`${label}: paragraph occurs more than once in body_markdown`);

  const normalizedBefore = normalizeText(before);
  const candidates = body.split(/\n\s*\n/);
  const matches = candidates
    .map((paragraph, index) => normalizeText(paragraph) === normalizedBefore ? { paragraph, index } : null)
    .filter(Boolean);
  if (matches.length !== 1) {
    throw new Error(`${label}: body_markdown paragraph synchronization found ${matches.length} normalized matches`);
  }
  candidates[matches[0].index] = after;
  return candidates.join("\n\n");
}

function replaceOneTextToken(article, beforeToken, afterText, label) {
  let matches = 0;
  if (String(article.intro ?? "").includes(beforeToken)) matches += 1;
  for (const section of jsonArray(article.sections)) {
    for (const paragraph of jsonArray(section.paragraphs)) if (String(paragraph).includes(beforeToken)) matches += 1;
    for (const bullet of jsonArray(section.bullets)) if (String(bullet).includes(beforeToken)) matches += 1;
  }
  if (matches !== 1) throw new Error(`${article.slug}: ${label} expected one structured token, found ${matches}`);

  const replace = (text) => String(text).replace(beforeToken, afterText);
  const oldIntro = String(article.intro ?? "");
  if (oldIntro.includes(beforeToken)) {
    const next = replace(oldIntro);
    article.body_markdown = replaceBodyParagraph(article.body_markdown, oldIntro, next, `${article.slug} ${label} intro`);
    article.intro = next;
    return;
  }
  for (const section of jsonArray(article.sections)) {
    for (let i = 0; i < jsonArray(section.paragraphs).length; i += 1) {
      const before = String(section.paragraphs[i]);
      if (!before.includes(beforeToken)) continue;
      const after = replace(before);
      article.body_markdown = replaceBodyParagraph(article.body_markdown, before, after, `${article.slug} ${label} paragraph`);
      section.paragraphs[i] = after;
      return;
    }
    for (let i = 0; i < jsonArray(section.bullets).length; i += 1) {
      const before = String(section.bullets[i]);
      if (!before.includes(beforeToken)) continue;
      const after = replace(before);
      article.body_markdown = replaceBodyParagraph(article.body_markdown, before, after, `${article.slug} ${label} bullet`);
      section.bullets[i] = after;
      return;
    }
  }
}

function replaceParagraphAt(article, section, index, after, label) {
  const before = String(section.paragraphs[index]);
  article.body_markdown = replaceBodyParagraph(article.body_markdown, before, after, `${article.slug} ${label}`);
  section.paragraphs[index] = after;
}

function insertParagraphAt(article, section, index, sentence, label) {
  const paragraphs = jsonArray(section.paragraphs);
  if (index < 0 || index > paragraphs.length) throw new Error(`${article.slug}: invalid insertion index ${index}`);

  if (index === 0) {
    const reference = String(paragraphs[0] ?? "");
    if (!reference) throw new Error(`${article.slug}: cannot insert before missing first paragraph`);
    article.body_markdown = replaceBodyParagraph(article.body_markdown, reference, `${sentence}\n\n${reference}`, `${article.slug} ${label}`);
  } else {
    const reference = String(paragraphs[index - 1]);
    article.body_markdown = replaceBodyParagraph(article.body_markdown, reference, `${reference}\n\n${sentence}`, `${article.slug} ${label}`);
  }
  paragraphs.splice(index, 0, sentence);
  section.paragraphs = paragraphs;
}


const RANK16_NEIGHBOR_PREFIX =
  "بنابراین بهترین استفاده از این مقاله، ساختن پرسش برای شناخت فرد است؛ نه چسباندن";

const LOCATOR_STOP_WORDS = new Set([
  "برای", "این", "است", "را", "در", "به", "از", "که", "یک", "فقط", "بخشی",
  "نشان", "می‌دهد", "میدهد", "روشن", "می‌کند", "میکند", "فرد", "مقاله",
]);

function locatorTokens(value) {
  return [...new Set(
    normalizeText(value)
      .replace(/[^\p{L}\p{N}]+/gu, " ")
      .split(" ")
      .map((token) => token.trim())
      .filter((token) => token.length >= 3 && !LOCATOR_STOP_WORDS.has(token)),
  )];
}

function overlapCount(left, right) {
  const rightSet = new Set(right);
  return left.reduce((sum, token) => sum + (rightSet.has(token) ? 1 : 0), 0);
}

function findRank16OverlapReference(article, plan) {
  const referenceTokens = locatorTokens(plan.referencePrefix);
  const neighborTokens = locatorTokens(RANK16_NEIGHBOR_PREFIX);
  const headingTokens = locatorTokens(plan.heading);
  const candidates = [];

  for (const [sectionIndex, section] of jsonArray(article.sections).entries()) {
    const paragraphs = jsonArray(section?.paragraphs);
    const sectionHeadingTokens = locatorTokens(section?.title ?? "");
    const headingOverlap = overlapCount(headingTokens, sectionHeadingTokens);

    for (const [refIndex, paragraph] of paragraphs.entries()) {
      const paragraphTokens = locatorTokens(paragraph);
      const referenceOverlap = overlapCount(referenceTokens, paragraphTokens);
      const nextTokens = refIndex + 1 < paragraphs.length
        ? locatorTokens(paragraphs[refIndex + 1])
        : [];
      const nextOverlap = overlapCount(neighborTokens, nextTokens);

      if (referenceOverlap < 3) continue;
      if (referenceOverlap === 3 && nextOverlap < 2 && headingOverlap < 2) continue;

      const score = referenceOverlap * 10 + nextOverlap * 4 + headingOverlap * 2;
      candidates.push({
        section,
        sectionIndex,
        refIndex,
        reference: String(paragraph),
        usedHeadingFallback: true,
        usedOverlapFallback: true,
        referenceOverlap,
        nextOverlap,
        headingOverlap,
        score,
        heading: String(section?.title ?? ""),
      });
    }
  }

  candidates.sort((left, right) =>
    right.score - left.score ||
    right.referenceOverlap - left.referenceOverlap ||
    right.nextOverlap - left.nextOverlap ||
    right.headingOverlap - left.headingOverlap ||
    left.sectionIndex - right.sectionIndex ||
    left.refIndex - right.refIndex
  );

  if (!candidates.length) {
    throw new Error(`${article.slug}: rank 16 overlap fallback found no qualifying paragraph`);
  }

  const best = candidates[0];
  const equallyStrong = candidates.filter((candidate) =>
    candidate.score === best.score &&
    candidate.referenceOverlap === best.referenceOverlap &&
    candidate.nextOverlap === best.nextOverlap &&
    candidate.headingOverlap === best.headingOverlap
  );

  if (equallyStrong.length === 1) {
    return best;
  }

  const expectedRefIndex = Number.isInteger(plan.paragraphOrdinal)
    ? plan.paragraphOrdinal - 1
    : null;
  if (expectedRefIndex !== null) {
    const ordinalMatches = equallyStrong.filter((candidate) => candidate.refIndex === expectedRefIndex);
    if (ordinalMatches.length === 1) {
      return {
        ...ordinalMatches[0],
        usedOrdinalTieBreak: true,
      };
    }
  }

  throw new Error(
    `${article.slug}: rank 16 overlap fallback remains ambiguous after roadmap tie-breaks ` +
    `(score ${best.score}; candidates ${equallyStrong.length})`
  );
}

function findAddReference(article, plan, options = {}) {
  const ordinal = plan.paragraphOrdinal;
  const allowHeadingFallback = options.allowHeadingFallback === true || plan.rank === 16;
  let sectionMatch = null;

  try {
    sectionMatch = findSection(article, plan.heading);
  } catch (error) {
    if (!allowHeadingFallback) throw error;
  }

  if (sectionMatch) {
    const paragraphs = jsonArray(sectionMatch.section.paragraphs);
    if (!Number.isInteger(ordinal) || ordinal < 1 || ordinal > paragraphs.length) {
      throw new Error(`${article.slug}: invalid roadmap paragraph ordinal ${ordinal}`);
    }
    return {
      section: sectionMatch.section,
      sectionIndex: sectionMatch.index,
      refIndex: ordinal - 1,
      reference: String(paragraphs[ordinal - 1]),
      usedHeadingFallback: false,
    };
  }

  if (!plan.referencePrefix) {
    throw new Error(`${article.slug}: cannot use heading fallback without a reference prefix`);
  }

  const expected = normalizeText(plan.referencePrefix);
  const matches = [];
  for (const [sectionIndex, section] of jsonArray(article.sections).entries()) {
    for (const [refIndex, paragraph] of jsonArray(section?.paragraphs).entries()) {
      if (normalizeText(paragraph).startsWith(expected)) {
        matches.push({
          section,
          sectionIndex,
          refIndex,
          reference: String(paragraph),
          usedHeadingFallback: true,
        });
      }
    }
  }

  if (matches.length === 1) {
    return matches[0];
  }

  if (plan.rank === 16) {
    const nextExpected = normalizeText(RANK16_NEIGHBOR_PREFIX);
    const neighborMatches = [];
    for (const [sectionIndex, section] of jsonArray(article.sections).entries()) {
      const paragraphs = jsonArray(section?.paragraphs);
      for (let nextIndex = 1; nextIndex < paragraphs.length; nextIndex += 1) {
        if (!normalizeText(paragraphs[nextIndex]).startsWith(nextExpected)) continue;
        neighborMatches.push({
          section,
          sectionIndex,
          refIndex: nextIndex - 1,
          reference: String(paragraphs[nextIndex - 1]),
          usedHeadingFallback: true,
          usedNeighborFallback: true,
          heading: String(section?.title ?? ""),
        });
      }
    }
    if (neighborMatches.length === 1) {
      return neighborMatches[0];
    }
    return findRank16OverlapReference(article, plan);
  }

  throw new Error(`${article.slug}: fallback locator expected one paragraph by prefix, found ${matches.length}`);
}

function assertAnchorLocation(article, plan) {
  const token = pageToken(plan.anchor);
  if (plan.heading === "مقدمه") {
    if (!String(article.intro ?? "").includes(token)) {
      throw new Error(`${article.slug}: expected anchor "${plan.anchor}" in intro`);
    }
    return;
  }

  let exactSection = null;
  try {
    exactSection = findSection(article, plan.heading).section;
  } catch (error) {
    if (plan.rank !== 16) throw error;
  }

  if (exactSection) {
    const sectionTexts = [...jsonArray(exactSection.paragraphs), ...jsonArray(exactSection.bullets)].map(String);
    if (!sectionTexts.some((text) => text.includes(token))) {
      throw new Error(`${article.slug}: expected anchor "${plan.anchor}" under H2 "${plan.heading}"`);
    }
    return;
  }

  const containing = jsonArray(article.sections).filter((section) =>
    [...jsonArray(section?.paragraphs), ...jsonArray(section?.bullets)]
      .some((text) => String(text).includes(token)),
  );
  if (containing.length !== 1) {
    throw new Error(`${article.slug}: fallback anchor location expected one containing section, found ${containing.length}`);
  }
}

function applyAdd(article, plan, options = {}) {
  const located = findAddReference(article, plan, {
    allowHeadingFallback: options.allowHeadingFallback,
  });
  const { section, refIndex, reference } = located;

  const allowPrefixDrift =
    options.allowPrefixDrift === true ||
    plan.rank === 53 ||
    located.usedNeighborFallback === true ||
    located.usedOverlapFallback === true;
  if (!allowPrefixDrift) {
    assertReferencePrefix(article, plan, reference);
  }

  const allowReferenceLinks =
    options.allowReferenceLinks === true ||
    [9, 16, 53, 59, 60].includes(plan.rank);
  if (!allowReferenceLinks && internalLinkCount(reference) !== plan.referenceParagraphLinkCount) {
    throw new Error(`${article.slug}: reference paragraph internal-link count drift; expected ${plan.referenceParagraphLinkCount}, got ${internalLinkCount(reference)}`);
  }

  const insertIndex = plan.placementMode === "BEFORE" ? refIndex : refIndex + 1;
  insertParagraphAt(article, section, insertIndex, plan.sentence, `ADD rank ${plan.rank}`);
}

function replaceSuffixFrom(before, starter, replacement, article, section, index, label) {
  const normalizedStarter = normalizeText(starter);
  const rawIndex = normalizeText(before).indexOf(normalizedStarter);
  if (rawIndex < 0) throw new Error(`${article.slug}: ${label} starter not found`);
  // Map the normalized starter back by searching its first distinctive literal words in original text.
  const firstWords = starter.slice(0, Math.min(starter.length, 24));
  let start = before.indexOf(firstWords);
  if (start < 0) {
    const compact = firstWords.replace(/\s+/g, " ");
    start = before.indexOf(compact);
  }
  if (start < 0) throw new Error(`${article.slug}: ${label} raw starter not found`);
  const after = `${before.slice(0, start).trimEnd()}${before.slice(0, start).trimEnd() ? " " : ""}${replacement}`;
  replaceParagraphAt(article, section, index, after, label);
}

function applySpecialReplace(article, plan) {
  const { section } = findSection(article, plan.heading);
  if (plan.rank === 3) {
    const before = String(section.paragraphs[0] ?? "");
    if (!before.trim()) throw new Error(`${article.slug}: rank 3 first paragraph is missing`);
    replaceParagraphAt(article, section, 0, plan.sentence, "rank 3 paragraph 1 rewrite");
    replaceOneTextToken(article, pageToken("ساخت چارت تولد در هالیوس"), "ساخت چارت تولد در هالیوس", "rank 3 secondary link de-link");
    return;
  }
  if (plan.rank === 4) {
    const before = String(section.paragraphs[1] ?? "");
    replaceSuffixFrom(before, "اگر می‌خواهید فاز تولد را", plan.sentence, article, section, 1, "rank 4 final sentence rewrite");
    return;
  }
  if (plan.rank === 5) {
    const token = pageToken("ساخت چارت تولد و دیدن ترنزیت‌های شخصی شهریور");
    const index = jsonArray(section.paragraphs).findIndex((p) => String(p).includes(token));
    if (index < 0) throw new Error(`${article.slug}: rank 5 misleading existing link paragraph not found`);
    replaceParagraphAt(article, section, index, plan.sentence, "rank 5 misleading paragraph rewrite");
    return;
  }
  if (plan.rank === 26) {
    const before = String(section.paragraphs[0] ?? "");
    replaceSuffixFrom(before, "برای شروع عملی", plan.sentence, article, section, 0, "rank 26 final sentence rewrite");
    return;
  }
  if (plan.rank === 38) {
    const before = String(section.paragraphs[1] ?? "");
    if (!normalizeText(before).startsWith("CTA هالیوس در این صفحه")) throw new Error(`${article.slug}: rank 38 second paragraph drift`);
    replaceParagraphAt(article, section, 1, plan.sentence, "rank 38 paragraph 2 rewrite");
    return;
  }
  throw new Error(`${article.slug}: unsupported REPLACE rank ${plan.rank}`);
}

