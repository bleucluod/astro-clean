function transformArticle(sourceArticle, plan, options = {}) {
  const article = deepClone(sourceArticle);
  if (article.slug !== plan.slug) {
    throw new Error(`${plan.slug}: slug mismatch against roadmap`);
  }
  if (options.enforceTitle !== false && article.title !== plan.title) {
    throw new Error(`${plan.slug}: title mismatch against roadmap`);
  }

  const initialStructured = structuredChartCount(article);
  const initialBody = bodyChartCount(article);
  if (options.enforceCurrentCount !== false && initialStructured !== plan.currentCount) {
    throw new Error(`${article.slug}: current structured /chart count drift; expected ${plan.currentCount}, got ${initialStructured}`);
  }
  if (initialBody !== initialStructured) {
    throw new Error(`${article.slug}: body_markdown /chart count ${initialBody} does not match structured count ${initialStructured}`);
  }

  const finalTokenAlreadyPresent = structuredTexts(article).some((text) => text.includes(pageToken(plan.anchor)));
  if (options.allowAlreadyApplied === true && finalTokenAlreadyPresent && plan.action === "ADD") {
    assertAnchorLocation(article, plan);
  } else if (plan.rank === 11) {
    applyRank11(article, plan);
  } else if (plan.rank === 55) {
    applyRank55(article, plan);
  } else if (plan.action === "ADD") {
    applyAdd(article, plan, {
      allowReferenceLinks: options.allowReferenceLinks,
      allowHeadingFallback: options.allowHeadingFallback,
      allowPrefixDrift: options.allowPrefixDrift,
    });
  } else if (plan.action === "REPLACE") {
    if (options.allowAlreadyApplied === true && finalTokenAlreadyPresent) {
      assertAnchorLocation(article, plan);
      if (plan.rank === 3 && structuredTexts(article).some((text) => text.includes(pageToken("ساخت چارت تولد در هالیوس")))) {
        replaceOneTextToken(article, pageToken("ساخت چارت تولد در هالیوس"), "ساخت چارت تولد در هالیوس", "rank 3 secondary link de-link");
      }
    } else {
      applySpecialReplace(article, plan);
    }
  } else if (plan.action === "KEEP") {
    assertAnchorLocation(article, plan);
  } else {
    throw new Error(`${article.slug}: unsupported action ${plan.action}`);
  }

  assertAnchorLocation(article, plan);
  const finalStructured = structuredChartCount(article);
  const finalBody = bodyChartCount(article);
  if (finalStructured < 1) throw new Error(`${article.slug}: final article has no contextual /chart link`);
  if (finalBody !== finalStructured) throw new Error(`${article.slug}: final body/structured /chart count mismatch`);

  for (const text of structuredTexts(article)) {
    if (/\[[^\]\r\n]+\]\(\/chart\)/.test(text)) {
      throw new Error(`${article.slug}: raw Markdown /chart syntax leaked into structured content`);
    }
  }

  const changed = JSON.stringify({ intro: article.intro, sections: article.sections, body: article.body_markdown }) !==
    JSON.stringify({ intro: sourceArticle.intro, sections: sourceArticle.sections, body: sourceArticle.body_markdown });
  return { article, changed, initialStructured, finalStructured };
}

function draftSnapshotToArticle(snapshot) {
  return {
    slug: String(snapshot?.slug ?? ""),
    title: String(snapshot?.title ?? ""),
    intro: String(snapshot?.intro ?? ""),
    key_points: jsonArray(snapshot?.keyPoints),
    sections: deepClone(jsonArray(snapshot?.sections)),
    body_markdown: String(snapshot?.bodyMarkdown ?? ""),
  };
}

function transformDraftSnapshot(sourceSnapshot, plan) {
  const snapshot = deepClone(sourceSnapshot);
  const sourceArticle = draftSnapshotToArticle(snapshot);
  const transformed = transformArticle(sourceArticle, plan, {
    enforceTitle: false,
    enforceCurrentCount: false,
    allowAlreadyApplied: true,
    allowReferenceLinks: true,
    allowHeadingFallback: plan.rank === 16,
    allowPrefixDrift: plan.rank === 53,
  });

  snapshot.intro = transformed.article.intro;
  snapshot.sections = transformed.article.sections;
  snapshot.bodyMarkdown = transformed.article.body_markdown;

  const changed = JSON.stringify({
    intro: snapshot.intro,
    sections: snapshot.sections,
    bodyMarkdown: snapshot.bodyMarkdown,
  }) !== JSON.stringify({
    intro: sourceSnapshot?.intro,
    sections: sourceSnapshot?.sections,
    bodyMarkdown: sourceSnapshot?.bodyMarkdown,
  });

  return {
    snapshot,
    changed,
    initialStructured: transformed.initialStructured,
    finalStructured: transformed.finalStructured,
  };
}

function buildBodyMarkdown(article) {
  const lines = [`# ${article.title}`, String(article.intro ?? ""), "## خلاصهٔ مقاله"];
  lines.push(...jsonArray(article.key_points).map((item) => `- ${item}`));
  for (const section of jsonArray(article.sections)) {
    lines.push(`## ${section.title}`);
    lines.push(...jsonArray(section.paragraphs).map(String));
    lines.push(...jsonArray(section.bullets).map((item) => `- ${item}`));
  }
  return lines.filter((line) => String(line).length > 0).join("\n\n");
}

