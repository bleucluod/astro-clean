function computeDraftMaintenanceState(item, liveRow, liveMeta) {
  const patchedSnapshot = deepClone(item.snapshot);
  const originalSnapshotVersion = Number(item.row.snapshot?.contentVersion ?? 1);
  const postLiveVersion = liveMeta
    ? Number(liveMeta.nextVersion)
    : Number(liveRow.content_version ?? 1);
  patchedSnapshot.contentVersion = Math.max(originalSnapshotVersion, postLiveVersion);

  const nextBaseRevision = liveMeta
    ? Number(liveMeta.revisionNumber)
    : Number(item.row.base_revision ?? 0);

  const snapshotChanged = JSON.stringify(patchedSnapshot) !== JSON.stringify(item.row.snapshot);
  const baseRevisionChanged = nextBaseRevision !== Number(item.row.base_revision ?? 0);

  return {
    patchedSnapshot,
    originalSnapshotVersion,
    postLiveVersion,
    nextBaseRevision,
    snapshotChanged,
    baseRevisionChanged,
    contentVersionRaised: patchedSnapshot.contentVersion > originalSnapshotVersion,
  };
}

