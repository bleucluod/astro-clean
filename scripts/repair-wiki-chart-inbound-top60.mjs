function collectLiveRowIssues(row, plan) {
  const issues = [];
  if (!row) {
    issues.push("production-article-missing");
    return issues;
  }
  if (String(row.title) !== plan.title) issues.push("production-title-drift");
  if (String(row.status) !== "published") issues.push("status-not-published");
  if (row.is_indexable !== true) issues.push("not-indexable");
  if (!row.published_at || Date.parse(String(row.published_at)) > Date.now()) issues.push("published-at-not-live");
  if (row.scheduled_for != null) issues.push("scheduled-for-not-null");
  if (row.deleted_at != null) issues.push("article-deleted");
  if (!String(row.body_markdown ?? "").trim()) issues.push("body-markdown-empty");
  return issues;
}

function collectOverwriteBlockers(row, plan) {
  const blockers = [];
  if (!row) return blockers;
  if (row.has_open_draft === true) {
    blockers.push({
      rank: plan.rank,
      slug: plan.slug,
      action: plan.action,
      type: "open-draft",
      count: Number(row.open_draft_count ?? 1),
    });
  }
  if (row.has_active_publish_job === true) {
    blockers.push({
      rank: plan.rank,
      slug: plan.slug,
      action: plan.action,
      type: "active-publish-job",
      count: Number(row.active_publish_job_count ?? 1),
    });
  }
  return blockers;
}

function assertLiveRow(row, plan) {
  const issues = collectLiveRowIssues(row, plan);
  if (issues.length) {
    throw new Error(`${plan.slug}: ${issues.join(",")}`);
  }
}

