async function verifyDraftSafeCommittedState(tx, liveRevisionMeta = null) {
  const rows = await loadRows(tx, { forUpdate: false });
  if (rows.length !== EXPECTED_ARTICLE_COUNT) {
    throw new Error(`post-apply live row count ${rows.length} != ${EXPECTED_ARTICLE_COUNT}`);
  }
  const rowsBySlug = new Map(rows.map((row) => [String(row.slug), row]));
  const finalLinks = await verifyAlreadyApplied(tx, rowsBySlug);

  for (const plan of PLAN) {
    const row = rowsBySlug.get(plan.slug);
    assertSpecialFinalState(rowToArticle(row), plan);
  }

  const draftRows = await loadDraftRowsForApply(tx, { forUpdate: false });
  if (draftRows.length !== EXPECTED_DRAFT_ARTICLES) {
    throw new Error(`post-apply draft row count ${draftRows.length} != ${EXPECTED_DRAFT_ARTICLES}`);
  }

  const planBySlug = new Map(PLAN.map((plan) => [plan.slug, plan]));
  let effectiveRevisionMeta = liveRevisionMeta;
  if (!effectiveRevisionMeta) {
    const draftArticleIds = draftRows.map((row) => String(row.article_id));
    const maintenanceRevisions = draftArticleIds.length
      ? await tx`
          select distinct on (article_id)
            article_id::text as article_id,
            revision_number
          from public.wiki_article_revisions
          where article_id = any(${draftArticleIds}::uuid[])
            and change_note = ${CHANGE_NOTE}
          order by article_id, revision_number desc
        `
      : [];
    effectiveRevisionMeta = new Map(
      maintenanceRevisions.map((row) => [
        String(row.article_id),
        { revisionNumber: Number(row.revision_number) },
      ]),
    );
  }

  let draftFinalLinks = 0;
  let draftContentVersionSafe = 0;
  let draftBaseRevisionSafe = 0;

  for (const draftRow of draftRows) {
    const plan = planBySlug.get(String(draftRow.slug));
    if (!plan) throw new Error(`${draftRow.slug}: post-apply draft plan missing`);

    const article = draftSnapshotToArticle(draftRow.snapshot);
    assertSpecialFinalState(article, plan);
    draftFinalLinks += structuredChartCount(article);

    const liveRow = rowsBySlug.get(String(draftRow.slug));
    if (!liveRow) throw new Error(`${draftRow.slug}: post-apply live row missing for draft`);
    const liveVersion = Number(liveRow.content_version ?? 1);
    const draftVersion = Number(draftRow.snapshot?.contentVersion ?? 1);
    if (draftVersion < liveVersion) {
      throw new Error(`${draftRow.slug}: draft contentVersion ${draftVersion} is behind live ${liveVersion}`);
    }
    draftContentVersionSafe += 1;

    if (effectiveRevisionMeta.has(String(draftRow.article_id))) {
      const expectedRevision = Number(effectiveRevisionMeta.get(String(draftRow.article_id)).revisionNumber);
      if (Number(draftRow.base_revision ?? 0) !== expectedRevision) {
        throw new Error(`${draftRow.slug}: draft base_revision ${draftRow.base_revision} != maintenance revision ${expectedRevision}`);
      }
    }
    draftBaseRevisionSafe += 1;
  }

  const activeJobs = rows
    .filter((row) => row.has_active_publish_job === true)
    .map((row) => String(row.slug));
  if (activeJobs.length) {
    throw new Error(`post-apply active publish jobs appeared: ${activeJobs.join(",")}`);
  }

  return {
    finalLinks,
    draftRowCount: draftRows.length,
    draftFinalLinks,
    draftContentVersionSafe,
    draftBaseRevisionSafe,
    activePublishJobCount: activeJobs.length,
  };
}

async function verifyAlreadyAppliedDraftSafe(tx, auditRow) {
  const verification = await verifyDraftSafeCommittedState(tx, null);
  const articleIds = PLAN.map((plan) => plan.slug);
  const revisionRows = await tx`
    select count(*)::integer as count
    from public.wiki_article_revisions revision
    join public.wiki_articles article on article.id = revision.article_id
    where article.slug = any(${articleIds}::text[])
      and revision.change_note = ${CHANGE_NOTE}
  `;
  const maintenanceRevisionCount = Number(revisionRows[0]?.count ?? 0);
  if (maintenanceRevisionCount !== EXPECTED_CHANGED_ARTICLES) {
    throw new Error(`already-applied maintenance revision count ${maintenanceRevisionCount} != ${EXPECTED_CHANGED_ARTICLES}`);
  }

  return {
    mode: "already-applied",
    runId: RUN_ID,
    candidateVersion: APPLY_CANDIDATE_VERSION,
    auditId: String(auditRow.id),
    maintenanceRevisionCount,
    ...verification,
  };
}

async function main() {
  const options = parseArgs();
  if (options.selfCheck) { assertSelfCheck(); return; }
  assertPlanShape();

  if (options.apply && options.confirm !== APPLY_CONFIRMATION) {
    throw new Error(`--apply requires --confirm=${APPLY_CONFIRMATION}`);
  }
  if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL is required for database dry-run/apply.");

  const { default: postgres } = await import("postgres");
  const sql = postgres(process.env.DATABASE_URL, {
    max: 1,
    prepare: false,
    connect_timeout: 8,
    connection: { default_transaction_read_only: !options.apply },
  });

  try {
    if (options.resumeVerify) {
      if (options.apply) throw new Error("--resume-verify cannot be combined with --apply");
      const result = await sql.begin("read only", async (tx) => {
        const readOnlyRows = await tx`show transaction_read_only`;
        const transactionReadOnly = String(readOnlyRows[0]?.transaction_read_only ?? "");
        if (transactionReadOnly !== "on") {
          throw new Error(`Resume verification transaction is not read-only: ${transactionReadOnly || "unknown"}`);
        }
        const verification = await runResumeVerification(tx);
        return { ...verification, transactionReadOnly };
      });
      console.log(options.compact ? JSON.stringify(result) : JSON.stringify(result, null, 2));
      return;
    }

    let transactionReadOnly = options.apply ? null : "unknown";

    const execute = async (tx) => {
      await tx`set local lock_timeout = '5s'`;

      if (options.apply) {
        const lock = await tx`select pg_try_advisory_xact_lock(hashtext(${RUN_ID})) as acquired`;
        if (lock[0]?.acquired !== true) {
          throw new Error("Another Top-60 chart inbound operation is running.");
        }
      } else {
        const readOnlyRows = await tx`show transaction_read_only`;
        transactionReadOnly = String(readOnlyRows[0]?.transaction_read_only ?? "");
        if (transactionReadOnly !== "on") {
          throw new Error(`Dry-run transaction is not read-only: ${transactionReadOnly || "unknown"}`);
        }
      }

      const rows = await loadRows(tx, { forUpdate: options.apply });
      if (rows.length !== EXPECTED_ARTICLE_COUNT) {
        const found = new Set(rows.map((row) => String(row.slug)));
        const missing = PLAN.filter((plan) => !found.has(plan.slug)).map((plan) => plan.slug);
        throw new Error(`production row count ${rows.length} != 60; missing=${missing.join(",")}`);
      }

      const rowsBySlug = new Map(rows.map((row) => [String(row.slug), row]));
      const planBySlug = new Map(PLAN.map((plan) => [plan.slug, plan]));

      const priorAudit = await tx`
        select id::text, after_summary
        from halleus_private.admin_audit_events
        where action = ${AUDIT_ACTION}
          and target_id = ${RUN_ID}
          and success = true
        order by created_at desc
        limit 1
      `;
      if (priorAudit.length) {
        return verifyAlreadyAppliedDraftSafe(tx, priorAudit[0]);
      }

      const prepared = [];
      const rowIssues = [];
      const transformFailures = [];
      const activeJobBlockers = [];
      let initialLinks = 0;
      let finalLinks = 0;

      for (const plan of PLAN) {
        const row = rowsBySlug.get(plan.slug);
        const issues = collectLiveRowIssues(row, plan);
        if (issues.length) {
          rowIssues.push({ rank: plan.rank, slug: plan.slug, action: plan.action, issues });
          continue;
        }

        if (row.has_active_publish_job === true) {
          activeJobBlockers.push({
            rank: plan.rank,
            slug: plan.slug,
            action: plan.action,
            type: "active-publish-job",
            count: Number(row.active_publish_job_count ?? 1),
          });
        }

        try {
          const source = rowToArticle(row);
          const transformed = transformArticle(source, plan);
          initialLinks += transformed.initialStructured;
          finalLinks += transformed.finalStructured;
          prepared.push({ plan, row, ...transformed });
        } catch (error) {
          transformFailures.push({
            rank: plan.rank,
            slug: plan.slug,
            action: plan.action,
            message: error instanceof Error ? error.message : String(error),
          });
        }
      }

      const changed = prepared.filter((item) => item.changed);
      const unchanged = prepared.filter((item) => !item.changed);
      const aggregateProblems = [];

      if (!rowIssues.length && !transformFailures.length) {
        if (initialLinks !== EXPECTED_INITIAL_CHART_LINKS) aggregateProblems.push(`aggregate initial links ${initialLinks} != 20`);
        if (finalLinks !== EXPECTED_FINAL_CHART_LINKS) aggregateProblems.push(`aggregate final links ${finalLinks} != 61`);
        if (changed.length !== EXPECTED_CHANGED_ARTICLES) aggregateProblems.push(`changed article count ${changed.length} != 47`);
        if (unchanged.length !== EXPECTED_UNTOUCHED_KEEP_ARTICLES || unchanged.some((item) => item.plan.action !== "KEEP")) {
          aggregateProblems.push("untouched article set is not the expected 13 KEEP rows");
        }
      }

      const draftRows = await loadDraftRowsForApply(tx, { forUpdate: options.apply });
      const { prepared: preparedDrafts, failures: draftFailures } = prepareDraftRows(draftRows, planBySlug);
      const draftContentChanged = preparedDrafts.filter((item) => item.changed);
      const draftContentUnchanged = preparedDrafts.filter((item) => !item.changed);

      if (draftRows.length !== EXPECTED_DRAFT_ARTICLES) {
        aggregateProblems.push(`draft row count ${draftRows.length} != ${EXPECTED_DRAFT_ARTICLES}`);
      }
      if (!draftFailures.length && preparedDrafts.length === EXPECTED_DRAFT_ARTICLES) {
        if (draftContentChanged.length !== EXPECTED_CHANGED_DRAFT_CONTENT) {
          aggregateProblems.push(`changed draft content ${draftContentChanged.length} != ${EXPECTED_CHANGED_DRAFT_CONTENT}`);
        }
        if (draftContentUnchanged.length !== EXPECTED_UNCHANGED_DRAFT_CONTENT) {
          aggregateProblems.push(`unchanged draft content ${draftContentUnchanged.length} != ${EXPECTED_UNCHANGED_DRAFT_CONTENT}`);
        }
      }

      const applyBlockers = [
        ...rowIssues.map((item) => ({ ...item, type: "live-row-issue" })),
        ...transformFailures.map((item) => ({ ...item, type: "transform-failure" })),
        ...activeJobBlockers,
        ...draftFailures,
        ...aggregateProblems.map((detail) => ({ type: "aggregate-problem", detail })),
      ];

      if (applyBlockers.length) {
        if (options.apply) {
          throw new Error(`Top-60 draft-safe apply blocked by ${applyBlockers.length} issue(s): ${JSON.stringify(applyBlockers)}`);
        }
        return {
          mode: "blocked-dry-run",
          runId: RUN_ID,
          candidateVersion: APPLY_CANDIDATE_VERSION,
          articleCount: rows.length,
          draftRowCount: draftRows.length,
          initialLinks,
          finalLinks,
          changedArticles: changed.length,
          untouchedKeepArticles: unchanged.length,
          changedDraftContent: draftContentChanged.length,
          unchangedDraftContent: draftContentUnchanged.length,
          blockers: applyBlockers,
          transactionReadOnly,
        };
      }

      if (!options.apply) {
        return {
          mode: "dry-run",
          runId: RUN_ID,
          candidateVersion: APPLY_CANDIDATE_VERSION,
          articleCount: rows.length,
          draftRowCount: draftRows.length,
          initialLinks,
          finalLinks,
          changedArticles: changed.length,
          untouchedKeepArticles: unchanged.length,
          changedDraftContent: draftContentChanged.length,
          unchangedDraftContent: draftContentUnchanged.length,
          transactionReadOnly,
        };
      }

      const changedArticleIds = changed.map((item) => String(item.row.id));
      const revisionCountBefore = await revisionCountForIds(tx, changedArticleIds);
      const liveRevisionMeta = new Map();

      for (const item of changed) {
        const revisionRows = await tx`
          select coalesce(max(existing.revision_number), 0)::integer + 1 as next_revision
          from public.wiki_article_revisions existing
          where existing.article_id = ${item.row.id}::uuid
        `;
        const revisionNumber = Number(revisionRows[0]?.next_revision ?? 1);
        const nextVersion = Number(item.row.content_version ?? 1) + 1;
        const snapshot = snapshotFromRow(item.row, item.article, nextVersion);

        await tx`
          insert into public.wiki_article_revisions (
            article_id, revision_number, snapshot, change_note, created_by,
            revision_status, published_at
          ) values (
            ${item.row.id}::uuid,
            ${revisionNumber},
            ${tx.json(snapshot)},
            ${CHANGE_NOTE},
            null,
            'published',
            now()
          )
        `;

        await tx`
          update public.wiki_articles
          set intro = ${item.article.intro},
              sections = ${tx.json(item.article.sections)},
              body_markdown = ${item.article.body_markdown},
              content_version = ${nextVersion},
              updated_at = now()
          where id = ${item.row.id}::uuid
        `;

        liveRevisionMeta.set(String(item.row.id), {
          slug: item.plan.slug,
          revisionNumber,
          nextVersion,
        });
      }

      let draftRowsUpdated = 0;
      let draftSnapshotUpdated = 0;
      let draftBaseRevisionUpdated = 0;
      let draftContentVersionRaised = 0;

      for (const item of preparedDrafts) {
        const articleId = String(item.row.article_id);
        const liveRow = rowsBySlug.get(item.plan.slug);
        if (!liveRow) throw new Error(`${item.plan.slug}: live row missing while applying draft`);

        const liveMeta = liveRevisionMeta.get(articleId);
        const maintenance = computeDraftMaintenanceState(item, liveRow, liveMeta);

        if (maintenance.snapshotChanged || maintenance.baseRevisionChanged) {
          await tx`
            update public.wiki_article_drafts
            set snapshot = ${tx.json(maintenance.patchedSnapshot)},
                base_revision = ${maintenance.nextBaseRevision}
            where article_id = ${articleId}::uuid
          `;
          draftRowsUpdated += 1;
        }
        if (maintenance.snapshotChanged) draftSnapshotUpdated += 1;
        if (maintenance.baseRevisionChanged) draftBaseRevisionUpdated += 1;
        if (maintenance.contentVersionRaised) draftContentVersionRaised += 1;
      }

      const revisionCountAfter = await revisionCountForIds(tx, changedArticleIds);
      if (revisionCountAfter - revisionCountBefore !== EXPECTED_CHANGED_ARTICLES) {
        throw new Error(`revision delta ${revisionCountAfter - revisionCountBefore} != ${EXPECTED_CHANGED_ARTICLES}`);
      }

      await tx`
        insert into halleus_private.admin_audit_events (
          actor_user_id, actor_role, action, target_type, target_id,
          before_summary, after_summary, reason, success, request_correlation_id
        ) values (
          null, 'system', ${AUDIT_ACTION}, 'wiki_graph', ${RUN_ID},
          ${tx.json({
            candidateVersion: APPLY_CANDIDATE_VERSION,
            roadmapCsvRawSha256: ROADMAP_CSV_RAW_SHA256,
            roadmapCsvSha256: ROADMAP_CSV_UTF8_SHA256,
            roadmapMdSha256: ROADMAP_MD_SHA256,
            initialLinks,
            articleCount: PLAN.length,
            draftRowCount: draftRows.length,
          })},
          ${tx.json({
            finalLinks,
            changedArticles: changed.length,
            untouchedKeepArticles: unchanged.length,
            changedDraftContent: draftContentChanged.length,
            unchangedDraftContent: draftContentUnchanged.length,
            draftRowsUpdated,
            draftSnapshotUpdated,
            draftBaseRevisionUpdated,
            draftContentVersionRaised,
            revisionsInserted: revisionCountAfter - revisionCountBefore,
          })},
          'Apply the approved Top-60 contextual /chart inbound-link execution map to live Wiki content and all open draft snapshots so future draft publication cannot overwrite the maintenance links.',
          true,
          ${RUN_ID}
        )
      `;

      const post = await verifyDraftSafeCommittedState(tx, liveRevisionMeta);
      if (post.finalLinks !== EXPECTED_FINAL_CHART_LINKS) {
        throw new Error(`post-apply final links ${post.finalLinks} != ${EXPECTED_FINAL_CHART_LINKS}`);
      }

      const auditRows = await tx`
        select count(*)::integer as count
        from halleus_private.admin_audit_events
        where action = ${AUDIT_ACTION}
          and target_id = ${RUN_ID}
          and success = true
      `;
      const auditCount = Number(auditRows[0]?.count ?? 0);
      if (auditCount !== 1) {
        throw new Error(`post-apply audit count ${auditCount} != 1`);
      }

      return {
        mode: "applied",
        runId: RUN_ID,
        candidateVersion: APPLY_CANDIDATE_VERSION,
        roadmapCsvRawSha256: ROADMAP_CSV_RAW_SHA256,
        roadmapCsvSha256: ROADMAP_CSV_UTF8_SHA256,
        roadmapMdSha256: ROADMAP_MD_SHA256,
        articleCount: rows.length,
        initialLinks,
        finalLinks,
        changedArticles: changed.length,
        untouchedKeepArticles: unchanged.length,
        draftRowCount: draftRows.length,
        changedDraftContent: draftContentChanged.length,
        unchangedDraftContent: draftContentUnchanged.length,
        draftRowsUpdated,
        draftSnapshotUpdated,
        draftBaseRevisionUpdated,
        draftContentVersionRaised,
        revisionsInserted: revisionCountAfter - revisionCountBefore,
        auditCount,
        post,
      };
    };

    const result = options.apply
      ? await sql.begin(execute)
      : await sql.begin("read only", execute);

    console.log(options.compact ? JSON.stringify(result) : JSON.stringify(result, null, 2));
  } finally {
    await sql.end({ timeout: 2 });
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});